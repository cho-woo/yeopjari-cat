"""Register the existing snack expressions and prop to Snowdrop's seated portrait.

The mask selects existing source pixels. Both pets render them with the same
eye-to-eye registration, on top of the original seated Snowdrop portrait.
"""
import argparse
import json
from functools import lru_cache
from pathlib import Path

import numpy as np
from PIL import Image, ImageChops

ROOT = Path(__file__).resolve().parents[1]
STYLES = ROOT / "assets/styled-sprites"
OUTPUT = STYLES / "snow-treat-details.png"
HEADER = ROOT / "src/snow_treat_registration.generated.hpp"
REFERENCE = 221


@lru_cache(maxsize=1)
def eye_transform():
    art = json.loads((STYLES / "art-provenance.json").read_text())
    cells = art["fallback_packing"]["cat.png"]["frames"]
    bx, by, bw, bh = cells[4]["registration_rect"]
    standing = max(cell["registration_rect"][3] for cell in cells[:6])
    geometry = json.loads((STYLES / "odd-eye-iris-regions.json").read_text())
    eyes = {a["base_resource_id"]: a["frames"] for a in geometry["atlases"]}

    def centers(labels):
        return np.array([(x + w/2, y + h/2) for x,y,w,h in
                         (e["rect"] for e in labels["eyes"])])

    # The neutral pair defines one similarity transform for the whole action.
    # Per-frame fitting would cancel the authored head and eyelid movements.
    src = centers(eyes[120][0])
    dst = (centers(eyes[101][4]) - (bx + bw/2, by + bh)) * REFERENCE / standing
    source_span = complex(*(src[1] - src[0]))
    ratio = complex(*(dst[1] - dst[0])) / source_span
    matrix = np.array([[ratio.real, -ratio.imag], [ratio.imag, ratio.real]])
    offset = dst[0] - matrix @ src[0]
    return ratio, matrix, offset, (bx, by, bw, bh), REFERENCE / standing


def register():
    ratio, matrix, offset, _, _ = eye_transform()
    prop = Image.open(STYLES / "identity-masks/c8-r120.png").convert("L")
    sheet = Image.new("RGBA", prop.size)
    yy, xx = np.mgrid[:256, :256]

    def feather(cx, cy, rx, ry):
        radius = np.hypot((xx-cx)/rx, (yy-cy)/ry)
        return np.clip((1-radius)*5, 0, 1)

    for i in range(24):
        if i in (0, 23):
            continue  # Both seated endpoints are the exact idle portrait.
        x, y = i%6*256, i//6*256
        cell = (x, y, x+256, y+256)
        # Include the whole animated muzzle and mouth, feathering inside
        # white fur. The surrounding cheeks, ear markings and body stay put.
        weight = feather(158, 142, 31, 27)
        if i in (5, 16, 17, 20, 21, 22):
            for cx, cy in src:
                weight = np.maximum(weight, feather(cx, cy-2, 38, 31))
        tube = np.asarray(prop.crop(cell), dtype=np.float32) / 255
        weight = np.maximum(weight, tube)
        layer = Image.new("RGBA", (256,256))
        layer.putalpha(Image.fromarray(np.rint(weight*255).astype(np.uint8)))
        sheet.paste(layer, (x,y))
    header = ("// Generated by tools/register_snow_treat.py from registered iris landmarks.\n"
              "#pragma once\nnamespace cat::snow_treat {\n"
              f"inline constexpr double reference={REFERENCE}, a={ratio.real:.10f}, b={ratio.imag:.10f},\n"
              f"    offsetX={offset[0]:.10f}, offsetY={offset[1]:.10f};\n}}\n")
    return sheet,header


ANDROID_ANCHOR = (128, 244)


@lru_cache(maxsize=3)
def registered_layers(coat):
    """Keep each animal's seated portrait throughout the registered snack performance."""
    _, matrix, relative, (x,y,w,h), scale = eye_transform()
    path = ROOT/'assets/cat.png' if coat==0 else STYLES/f'c{coat}-r101.png'
    with Image.open(path) as atlas:
        seated = atlas.convert("RGBA").crop((x,y,x+w,y+h))
    seated = seated.resize((round(w*scale),round(h*scale)),Image.Resampling.LANCZOS)
    base = Image.new("RGBA",(256,256))
    base.paste(seated,(round(ANDROID_ANCHOR[0]-seated.width/2),ANDROID_ANCHOR[1]-seated.height))
    inverse = np.linalg.inv(matrix)
    offset = -inverse @ (relative + ANDROID_ANCHOR)
    affine = tuple(np.column_stack((inverse,offset)).ravel())
    with Image.open(OUTPUT) as masks:
        return base, affine, masks.getchannel("A")


def android_frame(atlas, index, coat):
    base, affine, masks = registered_layers(coat)
    if index in (0, 23):
        return base.copy()
    x, y = index % 6 * 256, index // 6 * 256
    box = (x, y, x + 256, y + 256)
    details = atlas.crop(box)
    details.putalpha(ImageChops.multiply(details.getchannel("A"), masks.crop(box)))
    details = details.transform(base.size, Image.Transform.AFFINE, affine, Image.Resampling.BICUBIC)
    return Image.alpha_composite(base, details)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    sheet,header = register()
    if args.check:
        if sheet.tobytes() != Image.open(OUTPUT).convert("RGBA").tobytes() or HEADER.read_text()!=header:
            raise SystemExit("Snack layers differ from their registered sources")
    else:
        sheet.save(OUTPUT, optimize=True)
        HEADER.write_text(header, encoding="ascii", newline="\n")
