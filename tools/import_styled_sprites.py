#!/usr/bin/env python3
"""Import authored character PNGs while retaining the original pose programs.

Input: {"schema":1,"design":"tuxedo-kitten-v1","atlases":[
  {"character":8,"base_resource_id":113,"resource_id":500,"source":"groom.png"}]}
Sources must be real RGBA8 PNGs with the exact original atlas canvas dimensions.
The importer copies PNG bytes without recoloring, cropping, scaling or generating
art. It writes a separate appearance manifest/header/RC; care timing/registration
and the original PNGs are untouched. Run --require-character 8 for complete care
and fallback coverage, or --check to verify the imported bytes/generated metadata.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import struct
import sys

from import_care_sprites import ImportError, runtime_locomotion, load_entries, png_alpha, unique_object

ROOT=Path(__file__).resolve().parents[1]
DIRECTORY=Path('assets/styled-sprites')
CANONICAL=DIRECTORY/'manifest.json'
HEADER=Path('src/styled_sprites.generated.hpp')
RC=Path('src/styled_sprites.generated.rc')
REPORT=DIRECTORY/'import-report.json'
FALLBACK={101:'cat.png',102:'cat-actions.png',105:'cream-extra.png',
          106:'cream-gestures.png',107:'cream-recline.png',110:'cream-hang.png',112:'cream-sleep.png'}
CLIP_IDS={'groom':113,'sleep':114,'box':115,'fish':116,'punch':117,
          'eat':118,'jump':119,'treat':120,'walk':400,'run':400}


def require(condition,message):
    if not condition: raise ImportError(message)


def integer(value,name,low,high):
    require(type(value) is int and low<=value<=high,f'{name}: integer {low}..{high} required')
    return value


def digest(data):
    return hashlib.sha256(data).hexdigest()


def runtime_care_entries(root):
    # Use the same checked override selection as the ordinary care importer.
    # The canonical care manifest remains the original eight-drawing source.
    originals=load_entries(Path(root)/'assets/care-sprites/manifest.json')
    return runtime_locomotion(Path(root),originals)[0]


def base_sources(root,runtime=None):
    result={key:Path('assets')/value for key,value in FALLBACK.items()}
    for clip in runtime if runtime is not None else runtime_care_entries(root):
        if clip['character']==0 and clip['clip']!='box':
            result[clip['resource']]=Path(clip.get('asset_path',
                (Path('assets/care-sprites')/clip['filename']).as_posix()))
    return result


def generated(entries):
    header=['// Generated by tools/import_styled_sprites.py. Do not edit by hand.',
            '#pragma once','#include "cat_styled_sprite_assets.hpp"',
            'namespace cat::styled_assets {']
    for atlas in entries:
        if 'anchors' in atlas:
            name=f'kStyledAnchors{atlas["character"]}_{atlas["base_resource_id"]}'
            header.append(f'inline constexpr std::array<sprite_assets::Anchor,{len(atlas["anchors"])}> {name}{{{{')
            header.extend('    sprite_assets::Anchor{'+','.join(map(str,anchor))+'},' for anchor in atlas['anchors'])
            header.append('}};')
    header.append(f'inline constexpr std::array<Atlas,{len(entries)}> kStyledAtlases{{{{')
    rc=['// Generated by tools/import_styled_sprites.py. Do not edit by hand.']
    for atlas in entries:
        path=(DIRECTORY/atlas['source']).as_posix()
        header.append('    Atlas{'+','.join(map(str,[atlas['character'],atlas['base_resource_id'],
            atlas['resource_id'],atlas['image_width'],atlas['image_height']]))+
            ','+json.dumps(atlas['sha256'])+','+json.dumps(path)+','+
            (f'kStyledAnchors{atlas["character"]}_{atlas["base_resource_id"]}.data()' if 'anchors' in atlas else 'nullptr')+
            ','+str(len(atlas.get('anchors',[])))+','+str(atlas.get('reference_height',0))+'},')
        rc.append(f'{atlas["resource_id"]} RCDATA "../{path}"')
    header+=['}};','static_assert(ValidSet(kStyledAtlases), "Invalid authored appearance atlases");',
             '} // namespace cat::styled_assets','']
    return '\n'.join(header), '\n'.join(rc)+'\n'


def prepare_import(root,manifest_path=None,check=False,require_character=None):
    root=Path(root); path=Path(manifest_path) if manifest_path else root/CANONICAL
    require(path.is_file(),f'Missing authored appearance manifest: {path}')
    require(path.stat().st_size<=1024*1024,'Appearance manifest exceeds 1 MiB')
    manifest=json.loads(path.read_text(encoding='utf-8-sig'),object_pairs_hook=unique_object)
    require(isinstance(manifest,dict) and set(manifest)=={'schema','design','atlases'} and
            manifest['schema']==1,'Appearance manifest requires schema 1, design and atlases')
    require(isinstance(manifest['design'],str) and 1<=len(manifest['design'])<=160,'Design name required')
    require(isinstance(manifest['atlases'],list) and 1<=len(manifest['atlases'])<=160,'1..160 atlases required')
    runtime=runtime_care_entries(root)
    originals=base_sources(root,runtime); entries=[]; copies={}; resources=set(); pairs=set()
    fields={'character','base_resource_id','resource_id','source','sha256','base_sha256','base_source',
            'image_width','image_height','anchors','reference_height'}
    for index,item in enumerate(manifest['atlases']):
        name=f'atlases[{index}]'
        require(isinstance(item,dict) and set(item)<=fields and
                {'character','base_resource_id','resource_id','source'}<=set(item),f'{name}: invalid fields')
        character=integer(item['character'],name+'.character',1,10)
        base=integer(item['base_resource_id'],name+'.base_resource_id',1,499)
        resource=integer(item['resource_id'],name+'.resource_id',500,9999)
        require(base in originals,f'{name}: unknown base atlas {base}')
        require(resource not in resources and (character,base) not in pairs,f'{name}: duplicate resource or character/base pair')
        require(isinstance(item['source'],str) and item['source'].lower().endswith('.png'),f'{name}: PNG source path required')
        source=(path.parent/item['source']).resolve(); data=source.read_bytes()
        width,height,_=png_alpha(data)
        original_path=originals[base]; original=(root/original_path).read_bytes()
        require(original.startswith(b'\x89PNG\r\n\x1a\n') and len(original)>=24,'Invalid base PNG')
        require((width,height)==struct.unpack_from('>II',original,16),
                f'{name}: authored canvas {width}x{height} differs from original {original_path}')
        require(digest(data)!=digest(original),f'{name}: authored appearance must differ from the original Cream PNG')
        entry={'character':character,'base_resource_id':base,'resource_id':resource,
               'source':f'c{character}-r{base}.png','image_width':width,'image_height':height,
               'sha256':digest(data),'base_source':original_path.as_posix(),'base_sha256':digest(original)}
        if 'reference_height' in item:
            value=item['reference_height']
            require(type(value) in (int,float) and math.isfinite(value) and 0<value<=16384,
                    f'{name}: invalid common reference_height')
            entry['reference_height']=value
        if 'anchors' in item:
            layouts=[clip for clip in runtime if clip['character']==0 and clip['resource']==base]
            anchors=item['anchors']
            require(layouts and isinstance(anchors,list) and 'frames' in layouts[0] and
                    all(len(anchors)==len(layout['frames']) for layout in layouts),
                    f'{name}: one anchor per runtime care frame required')
            for frame,anchor in enumerate(anchors):
                for layout in layouts:
                    rect=layout['frames'][frame]['rect']
                    require(isinstance(anchor,list) and len(anchor)==2 and all(type(value) in (int,float) and
                        math.isfinite(value) and 0<=value<=rect[2+axis] for axis,value in enumerate(anchor)),
                        f'{name}: invalid local anchor for {layout["clip"]} frame {frame}')
            entry['anchors']=anchors
        for field in ('sha256','base_sha256','base_source','image_width','image_height'):
            if field in item:require(item[field]==entry[field],f'{name}: {field} mismatch')
        entries.append(entry); copies[root/DIRECTORY/entry['source']]=data
        resources.add(resource);pairs.add((character,base))
    entries.sort(key=lambda atlas:(atlas['character'],atlas['base_resource_id']))
    if require_character is not None:
        integer(require_character,'required character',1,10)
        missing=sorted(set(originals)-{base for character,base in pairs if character==require_character})
        require(not missing,f'Incomplete character {require_character}; missing base atlases {missing}')
    canonical={'schema':1,'design':manifest['design'],'atlases':entries}
    header,rc=generated(entries)
    report={'schema':1,'design':manifest['design'],'atlases':len(entries),
            'characters':sorted({atlas['character'] for atlas in entries}),
            'resource_ids':sorted(resources),'complete_characters':sorted(character for character in
                {atlas['character'] for atlas in entries} if all((character,base) in pairs for base in originals)),
            'sheet_pixels':sum(a['image_width']*a['image_height'] for a in entries),
            'largest_decoded_atlas_bytes':max(a['image_width']*a['image_height']*4 for a in entries),
            'sources':entries}
    outputs={root/CANONICAL:(json.dumps(canonical,indent=2,ensure_ascii=False)+'\n').encode(),
             root/HEADER:header.encode(),root/RC:rc.encode(),
             root/REPORT:(json.dumps(report,indent=2,ensure_ascii=False)+'\n').encode()}
    outputs.update(copies)
    for destination,data in outputs.items():
        if check:require(destination.is_file() and destination.read_bytes()==data,f'Authored asset drift: {destination}')
    if not check:
        for destination,data in outputs.items():
            destination.parent.mkdir(parents=True,exist_ok=True)
            temporary=destination.with_name(destination.name+'.tmp')
            temporary.write_bytes(data);temporary.replace(destination)
    return report


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest',type=Path)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--require-character',type=int)
    arguments=parser.parse_args()
    try:
        report=prepare_import(ROOT,arguments.manifest,arguments.check,arguments.require_character)
    except (OSError,ValueError,ImportError) as error:
        print(f'Authored appearance import failed: {error}',file=sys.stderr);return 1
    print(json.dumps({key:value for key,value in report.items() if key!='sources'},ensure_ascii=False))
    return 0

if __name__=='__main__':
    raise SystemExit(main())
